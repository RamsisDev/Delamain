import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { GitWorkspace, NodeCommandRunner, NodeToolHost } from "../src/index.ts";
import { tempRepo } from "./helpers.ts";

describe("git workspace", () => {
  it("runs tasks in worktrees, commits only the edit list and merges into the session branch", async () => {
    const repo = tempRepo({ "src/a.ts": "export const a = 1;\n", "src/b.ts": "export const b = 1;\n", "uv.lock": "v1\n" });
    const storage = mkdtempSync(join(tmpdir(), "harness-storage-"));
    const ws = new GitWorkspace(repo, storage);
    const session = await ws.startSession("s1");
    expect(session.branch).toBe("harness/s1");

    const t1 = await ws.createTaskWorktree("s1", "t1", 0);
    expect(t1.created).toBe(true);
    writeFileSync(join(t1.path, "src/a.ts"), "export const a = 2;\n");
    writeFileSync(join(t1.path, "src/new.ts"), "export const n = 1;\n");
    writeFileSync(join(t1.path, "uv.lock"), "v2 regenerated by setup\n");
    const diff = await ws.diff(t1.path, ["src/a.ts", "src/new.ts"]);
    expect(diff).toContain("+export const a = 2;");
    expect(diff).toContain("src/new.ts");
    expect(diff).not.toContain("uv.lock");

    const checkpoint = await ws.checkpoint(t1.path);
    writeFileSync(join(t1.path, "src/a.ts"), "export const a = 3;\n");
    expect(await ws.diffSince(t1.path, checkpoint)).toContain("+export const a = 3;");

    const merged = await ws.commitAndMerge("s1", t1.path, "t1", ["src/a.ts", "src/new.ts"], "harness(t1): a");
    expect(merged.ok).toBe(true);
    await ws.removeTaskWorktree(t1.path);

    const sessionFile = readFileSync(join(session.path, "src/a.ts"), "utf8");
    expect(sessionFile).toBe("export const a = 3;\n");
    expect(readFileSync(join(session.path, "uv.lock"), "utf8")).toBe("v1\n");
    expect(readFileSync(join(repo, "src/a.ts"), "utf8")).toBe("export const a = 1;\n");
    expect((await ws.sessionDiff("s1"))).toContain("src/new.ts");

    // A dependent task starts from the session branch, so it already has t1's work.
    const t2 = await ws.createTaskWorktree("s1", "t2", 0);
    expect(readFileSync(join(t2.path, "src/new.ts"), "utf8")).toContain("n = 1");

    const files = await ws.sessionFiles("s1");
    expect(files.sort()).toEqual(["src/a.ts", "src/new.ts"]);
    const commit = await ws.commitToCurrentBranch("s1", "harness: session s1");
    expect(commit.ok).toBe(true);
    expect(readFileSync(join(repo, "src/a.ts"), "utf8")).toBe("export const a = 3;\n");
    await ws.cleanupSession("s1", true);
  });

  it("reports merge conflicts instead of resolving them", async () => {
    const repo = tempRepo({ "src/a.ts": "one\n" });
    const ws = new GitWorkspace(repo, mkdtempSync(join(tmpdir(), "harness-storage-")));
    await ws.startSession("s2");
    const a = await ws.createTaskWorktree("s2", "ta", 0);
    const b = await ws.createTaskWorktree("s2", "tb", 0);
    writeFileSync(join(a.path, "src/a.ts"), "from a\n");
    writeFileSync(join(b.path, "src/a.ts"), "from b\n");
    expect((await ws.commitAndMerge("s2", a.path, "ta", ["src/a.ts"], "a")).ok).toBe(true);
    const conflict = await ws.commitAndMerge("s2", b.path, "tb", ["src/a.ts"], "b");
    expect(conflict).toEqual({ ok: false, conflicts: ["src/a.ts"] });
  });

  it("still shows the committed diff after keeping the session branch and removing its worktree", async () => {
    const repo = tempRepo({ "sum.js": "exports.sum = (a, b) => a - b;\n" });
    const ws = new GitWorkspace(repo, mkdtempSync(join(tmpdir(), "harness-storage-")));
    const session = await ws.startSession("kept");
    writeFileSync(join(session.path, "sum.js"), "exports.sum = (a, b) => a + b;\n");
    await ws.finalizeSession("kept", "Fix sum");
    const before = await ws.sessionDiff("kept");
    await ws.cleanupSession("kept", false);
    expect(await ws.sessionDiff("kept")).toBe(before);
    expect(before).toContain("+exports.sum = (a, b) => a + b;");
    expect(readFileSync(join(repo, "sum.js"), "utf8")).toContain("a - b");
    await ws.cleanupSession("kept", true);
  });
});

describe("node command runner and tool host", () => {
  it("captures output, exit codes and timeouts", async () => {
    const runner = new NodeCommandRunner();
    const ok = await runner.run({ command: "echo hello && exit 3", cwd: tmpdir(), timeoutMs: 5000 });
    expect(ok).toMatchObject({ exitCode: 3, timedOut: false });
    expect(ok.output).toContain("hello");
    const slow = await runner.run({ command: 'node -e "setTimeout(() => {}, 5000)"', cwd: tmpdir(), timeoutMs: 200 });
    expect(slow.timedOut).toBe(true);
    expect(slow.durationMs).toBeLessThan(3000);
  });

  it("keeps file tools inside the working directory", async () => {
    const repo = tempRepo({ "src/a.ts": "const x = 1;\n" });
    const host = new NodeToolHost();
    expect(await host.readFile(repo, "src/a.ts")).toContain("x = 1");
    await expect(host.readFile(repo, "../etc/passwd")).rejects.toThrow("outside");
    await host.writeFile(repo, "src/deep/new.ts", "y");
    expect(await host.listFiles(repo, ".", "src/**")).toEqual(["src/a.ts", "src/deep/new.ts"]);
    expect((await host.search(repo, "x = 1"))[0]).toMatchObject({ file: "src/a.ts", line: 1 });
  });
});
